# ── dispatch ─────────────────────────────────────────────────────────────────

def build_email(tool: str, payloads: List[Dict[str, Any]],
                fmt: str) -> Tuple[str, str, Dict[str, Any]]:
    """tool: 'bonds' | 'loans'. payloads: all tranche payloads for one deal.

    Returns ``(subject, body_html, meta)`` where ``meta`` is::

        {"rendered_fields": [app column names the format actually printed],
         "gap_fill": {pool name -> [picks, in render order],
                      "settlement_period": [n, ...],
                      "rating_outlook": "Stable" | absent}}

    ``rendered_fields`` is the denominator of the extraction-accuracy score
    (spec §18.6); ``gap_fill`` carries the values the template invented, which
    only this module knows and ``expected_writer`` needs. Only the bond
    renderers are instrumented — Bonds is the v1 comparison scope, so a loan
    email reports whatever the shared helpers happened to mark.
    """
    rec = _Recorder()
    _state.rec = rec
    try:
        if tool == "loans":
            subject, body = build_loan_email(payloads, fmt or DEFAULT_LOAN_FORMAT)
        else:
            subject, body = build_bond_email(payloads, fmt or DEFAULT_BOND_FORMAT)
    finally:
        _state.rec = None
    return subject, body, rec.meta()

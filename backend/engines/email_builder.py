"""Broker-email builder — renders generated bond/loan payloads as broker-style
HTML emails that mirror the Genesis Email Parsing POC samples.

The engines already build a full ``DETAILS`` dict per tranche; this module just
re-renders that same data as the natural-language / labelled-block emails that
banks send, so the Genesis email-parsing pipeline can be fed synthetic mail.

Fields that the payload generators do not produce (Call Protection, Non-Call
period, First Reset date, free-text business/UoP prose, …) are filled two ways:

* **Boilerplate** — a fixed canned string, identical on every email
  (see ``_BOILERPLATE``).
* **Random pool** — one value picked from a small realistic list each time
  (see ``_POOLS`` and ``_pick``).

No external dependencies and no network — pure string building, so it is unit
testable without Outlook or credentials.

``build_email`` also reports **what it actually rendered** (spec §18.6): a set
of canonical field names (app column names, so the comparator can intersect
them with ``field_map.csv``) plus the gap-fill values it picked. A field the
generator produced but the chosen format never printed cannot be extracted by
the email-parsing agent, so scoring it would understate accuracy; and a value
the *template* invented (the use-of-proceeds prose, the ``T+n`` label, the
rating outlook) is only knowable here, so the expectation writer needs it back.
"""
